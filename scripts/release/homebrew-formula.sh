#!/usr/bin/env bash
# Writes a Homebrew formula for one release to stdout.
#
#   homebrew-formula.sh <version> <dist-dir> [download-base]
#
# The formula installs the prebuilt binary for the machine's OS and CPU and
# pins each one by the SHA-256 in its sidecar in <dist-dir>, so it has to be
# generated from the exact files the release attaches. download-base defaults
# to this repository's releases and follows the launcher's layout,
# <base>/v<version>/<asset>, so verification can point it at a local server.
#
# It is attached to the release as memoar.rb. Publishing it to a tap is a
# separate, human decision, documented in docs/releasing.md.
set -euo pipefail

version=${1:?usage: homebrew-formula.sh <version> <dist-dir> [download-base]}
dist=${2:?dist directory required}
base=${3:-https://github.com/almyty-inc/memoar/releases/download}
base=${base%/}

digest() {
  local sidecar="$dist/$1.sha256"
  if [ ! -f "$sidecar" ]; then
    echo "homebrew-formula: $sidecar is missing" >&2
    exit 1
  fi
  local value
  value=$(awk 'NR == 1 { print tolower($1) }' "$sidecar")
  if ! printf '%s' "$value" | grep -Eq '^[0-9a-f]{64}$'; then
    echo "homebrew-formula: $sidecar does not start with a SHA-256 digest" >&2
    exit 1
  fi
  printf '%s' "$value"
}

block() {
  local asset=$1
  printf '      url "%s/v%s/%s"\n' "$base" "$version" "$asset"
  printf '      sha256 "%s"\n' "$(digest "$asset")"
}

cat <<RUBY
# Generated by scripts/release/homebrew-formula.sh for Memoar ${version}.
# Do not edit by hand. Regenerate it from the release assets instead.
class Memoar < Formula
  desc "Capture agent and CLI for the Memoar coding-session archive"
  homepage "https://github.com/almyty-inc/memoar"
  version "${version}"
  license "Apache-2.0"

  on_macos do
    on_arm do
$(block memoar-aarch64-apple-darwin)
    end
    on_intel do
$(block memoar-x86_64-apple-darwin)
    end
  end

  on_linux do
    on_arm do
$(block memoar-aarch64-unknown-linux-gnu)
    end
    on_intel do
$(block memoar-x86_64-unknown-linux-gnu)
    end
  end

  def install
    binary = Dir["memoar-*"].first
    odie "the downloaded release asset is missing" if binary.nil?
    bin.install binary => "memoar"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/memoar --version")
    system bin/"memoar", "sources", "list", "--capture-home", testpath
  end
end
RUBY
